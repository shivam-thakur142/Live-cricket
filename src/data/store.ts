function e(wides = 0, noBalls = 0, byes = 0, legByes = 0): Extras {
  return { wides, noBalls, byes, legByes, total: wides + noBalls + byes + legByes };
}

function b(
  playerId: string,
  playerName: string,
  runs: number,
  balls: number,
  fours: number,
  sixes: number,
  dismissal: string
): BattingLineup {
  return {
    playerId,
    playerName,
    runs,
    balls,
    fours,
    sixes,
    strikeRate: balls > 0 ? Number(((runs / balls) * 100).toFixed(2)) : 0,
    dismissal,
  };
}

function bo(
  playerId: string,
  playerName: string,
  overs: number,
  maidens: number,
  runs: number,
  wickets: number
): BowlingLineup {
  return {
    playerId,
    playerName,
    overs,
    maidens,
    runs,
    wickets,
    economy: overs > 0 ? Number((runs / overs).toFixed(2)) : 0,
  };
}

